import { test } from '@japa/runner';

import { MarkdownService } from '#markdown/markdown_service';
import { FakeYoutubeService } from '#tests/helpers/fake_youtube_service';

function makeMarkdownService(): MarkdownService {
	return new MarkdownService(new FakeYoutubeService([]));
}

test.group('MarkdownService.markdownToHtmlWithToc - table of contents', () => {
	test('should extract heading levels, ids and text, including nested inline markup', async ({
		assert,
	}) => {
		const markdown = [
			'# Guide Title',
			'',
			'## Installation Steps',
			'',
			'### Nested `code` Heading',
			'',
		].join('\n');

		const { toc } = await makeMarkdownService().markdownToHtmlWithToc(markdown);

		assert.deepEqual(toc, [
			{ level: 1, text: 'Guide Title', id: 'guide-title' },
			{ level: 2, text: 'Installation Steps', id: 'installation-steps' },
			{ level: 3, text: 'Nested code Heading', id: 'nested-code-heading' },
		]);
	});
});

test.group('MarkdownService.markdownToHtmlWithToc - security', () => {
	test('should strip <script> tags and their content entirely', async ({
		assert,
	}) => {
		const { html } = await makeMarkdownService().markdownToHtmlWithToc(
			`<script>alert('xss')</script>`
		);

		assert.notInclude(html, "alert('xss')");
	});

	test('should strip onerror= attributes from otherwise allowed tags', async ({
		assert,
	}) => {
		const { html } = await makeMarkdownService().markdownToHtmlWithToc(
			`<img src="x" onerror="alert('xss')">`
		);

		assert.notInclude(html, 'onerror');
	});

	test('should strip javascript: hrefs', async ({ assert }) => {
		const { html } = await makeMarkdownService().markdownToHtmlWithToc(
			`<a href="javascript:alert('xss')">click me</a>`
		);

		assert.notInclude(html, 'javascript:');
	});

	test('should strip <iframe> elements entirely', async ({ assert }) => {
		const { html } = await makeMarkdownService().markdownToHtmlWithToc(
			`<iframe src="https://evil.example.com"></iframe>`
		);

		assert.notInclude(html, '<iframe');
	});

	test('should strip the style attribute', async ({ assert }) => {
		const { html } = await makeMarkdownService().markdownToHtmlWithToc(
			`<p style="color:red">styled paragraph</p>`
		);

		assert.notInclude(html, 'style=');
	});

	test('should keep <details> and <summary> elements', async ({ assert }) => {
		const markdown = [
			'<details>',
			'<summary>Click to expand</summary>',
			'Hidden content',
			'</details>',
		].join('\n');

		const { html } =
			await makeMarkdownService().markdownToHtmlWithToc(markdown);

		assert.include(html, '<summary>Click to expand</summary>');
	});

	test('should keep the fenced code language class', async ({ assert }) => {
		const markdown = ['```js', 'const x = 1;', '```'].join('\n');

		const { html } =
			await makeMarkdownService().markdownToHtmlWithToc(markdown);

		assert.include(html, 'class="language-js"');
	});

	test('should keep heading ids generated by rehype-slug', async ({
		assert,
	}) => {
		const { html } =
			await makeMarkdownService().markdownToHtmlWithToc('# Guide Title');

		assert.include(html, 'id="guide-title"');
	});
});
